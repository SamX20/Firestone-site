function setLanguage(next) {
  language = next === "en" ? "en" : "ar";
  const dictionary = copy[language];
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  $$("[data-i18n]").forEach((node) => {
    const value = dictionary[node.dataset.i18n];
    if (value !== undefined) {
      // Icon containers never carry data-i18n, so changing language preserves icons.
      node.textContent = value;
      node.style.whiteSpace = value.includes("\n") ? "pre-line" : "";
    }
  });
  $$("[data-label]").forEach((node) => {
    const key = node.dataset.label;
    node.setAttribute(
      "aria-label",
      key.startsWith("project")
        ? (language === "ar" ? "عرض: " : "View: ") +
            dictionary["projectTitle" + key.slice(7)]
        : dictionary[key],
    );
  });
  $$("[data-label]").forEach((node) => {
    if (node.matches("button")) node.title = node.getAttribute("aria-label");
  });
  $$("[data-alt]").forEach((node) => {
    node.alt = dictionary[node.dataset.alt];
  });
  $$("[data-placeholder]").forEach((node) => {
    node.placeholder = dictionary[node.dataset.placeholder];
  });
  $("[data-lang-toggle] span").textContent = language === "ar" ? "EN" : "عربي";
  $("[data-lang-toggle]").setAttribute(
    "aria-label",
    language === "ar" ? "Switch to English" : "التبديل إلى العربية",
  );
  menuButton.setAttribute(
    "aria-label",
    dictionary[nav.classList.contains("is-open") ? "closeMenu" : "menu"],
  );
  $$("[data-wa-source]").forEach((link) => {
    link.href = whatsappUrl + "?text=" + encodeURIComponent(dictionary.waGreeting);
  });
  updateWorkMore();
  document.title = dictionary.title;
  $('meta[name="description"]').content = dictionary.description;
  updateServiceImage();
  if (managedProjects) renderManagedProjects();
  if (lightbox.open) updateLightbox();
  try {
    localStorage.setItem("firestone-language", language);
  } catch {}
  const url = new URL(location.href);
  if (language === "en") url.searchParams.set("lang", "en");
  else url.searchParams.delete("lang");
  history.replaceState(history.state, "", url);
  $('link[rel="canonical"]').href =
    "https://firestonejo.com/" + (language === "en" ? "?lang=en" : "");
}
